function runSync(isDryRun = false) {
  console.log('=====================================================');
  console.log(' CHAKRI SHEBA ? TELETALK OFFICIAL JOB SYNCHRONIZER   ');
  console.log(' Execution Mode: ' + (isDryRun ? 'DRY RUN (Preview Only)' : 'LIVE APPLY (Write to Database)'));
  console.log(' Local Time:     ' + new Date().toISOString());
  console.log('=====================================================\n');

  const raw = fs.readFileSync(STORE_PATH, 'utf8');
  const store = JSON.parse(raw);
  if (!store.jobs) store.jobs = {};
  if (!store.adminAuditLogs) store.adminAuditLogs = [];

  const existingJobs = Object.values(store.jobs);
  console.log('Existing stored jobs count: ' + existingJobs.length);

  let createdCount = 0;
  let updatedCount = 0;
  let duplicatesDetected = 0;
  let unchangedCount = 0;

  const changeLog = [];

  for (const circular of VERIFIED_CIRCULARS) {
    const match = existingJobs.find(j => 
      (j.refNo && j.refNo === circular.refNo) ||
      (j.id && j.id === ('job-teletalk-' + circular.refNo.toLowerCase().replace(/[^a-z0-9]/g, '-').slice(0, 24))) ||
      (j.organization === circular.organization && j.title.trim() === circular.title.trim())
    );

    if (match) {
      duplicatesDetected++;
      const needsUpdate = 
        match.deadline !== circular.deadline ||
        match.totalPosts !== circular.totalPosts ||
        match.status !== circular.status ||
        match.daysRemaining !== circular.daysRemaining;

      if (needsUpdate) {
        updatedCount++;
        changeLog.push({
          action: 'UPDATE',
          id: match.id,
          title: match.title,
          refNo: circular.refNo,
          status: circular.status,
          deadline: circular.deadline
        });

        if (!isDryRun) {
          store.jobs[match.id] = {
            ...match,
            ...circular,
            id: match.id,
            updatedAt: new Date().toISOString()
          };
        }
      } else {
        unchangedCount++;
      }
    } else {
      createdCount++;
      const newId = 'job-teletalk-' + circular.refNo.toLowerCase().replace(/[^a-z0-9]/g, '-').slice(0, 24);
      changeLog.push({
        action: 'CREATE',
        id: newId,
        title: circular.title,
        refNo: circular.refNo,
        status: circular.status,
        deadline: circular.deadline
      });

      if (!isDryRun) {
        store.jobs[newId] = {
          id: newId,
          ...circular,
          logo: 'https://images.unsplash.com/photo-1541872703-74c5e44368f9?auto=format&fit=crop&w=120&q=80',
          circularImage: 'https://images.unsplash.com/photo-1586281380349-632531db7ed4?auto=format&fit=crop&w=600&q=80',
          audioSummary: circular.title + ' ???????? ?????? ??? ??? ' + circular.deadline + '?',
          createdAt: new Date().toISOString(),
          lastVerifiedAt: new Date().toISOString()
        };
      }
    }
  }

  console.log('--- SYNCHRONIZATION MANIFEST ---');
  console.log('Discovered & Audited Portals: ' + AUDITED_PORTALS.length);
  console.log('Verified Circulars Processed: ' + VERIFIED_CIRCULARS.length);
  console.log('New Jobs to Create:           ' + createdCount);
  console.log('Existing Jobs to Update:       ' + updatedCount);
  console.log('Duplicates Detected & Merged:  ' + duplicatesDetected);
  console.log('Unchanged Identical Jobs:      ' + unchangedCount);
  console.log('\n--- DETAILED CHANGE PREVIEW ---');
  console.table(changeLog);

  if (!isDryRun) {
    store.adminAuditLogs.unshift({
      id: 'AUDIT-' + Date.now(),
      action: 'TELETALK_SYNC',
      actor: 'ADMIN_AUTONOMOUS_SYNC_ENGINE',
      timestamp: new Date().toISOString(),
      details: 'Synced ' + VERIFIED_CIRCULARS.length + ' official circulars (Created: ' + createdCount + ', Updated: ' + updatedCount + ', Duplicates Merged: ' + duplicatesDetected + ')'
    });

    fs.writeFileSync(STORE_PATH, JSON.stringify(store, null, 2), 'utf8');
    console.log('\n? SUCCESS: Saved changes to local_store.json. Total jobs now: ' + Object.keys(store.jobs).length);
  } else {
    console.log('\n[DRY RUN COMPLETE]: No changes were written to disk.');
  }

  return {
    portalsAudited: AUDITED_PORTALS,
    totalVerified: VERIFIED_CIRCULARS.length,
    created: createdCount,
    updated: updatedCount,
    duplicatesDetected,
    unchanged: unchangedCount,
    changeLog
  };
}

module.exports = { runSync, AUDITED_PORTALS, VERIFIED_CIRCULARS };

if (require.main === module) {
  const isApply = process.argv.includes('--apply');
  runSync(!isApply);
}
